export function getItemsByCategory(category: string): ItemDef[] {
  const all = getAllItems().filter((i) => i.price !== undefined && i.price > 0);
  if (category === "todas" || !category) return all;
  if (category === "herramienta") return all.filter((i) => i.category === "herramienta");
  if (category === "consumible") return all.filter((i) => i.category === "consumible");
  if (category === "pesca") return all.filter((i) => i.category === "pesca");
  if (category === "caza") return all.filter((i) => i.category === "caza");
  if (category === "coleccion") return all.filter((i) => i.category === "coleccion");
  if (category === "cosmetico") return all.filter((i) => i.category === "cosmetico");
  return all.filter((i) => i.category === category);
}
