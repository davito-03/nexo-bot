export function isTrainerItem(id: string): boolean {
  return (
    id === "pokeball" ||
    id === "superball" ||
    id === "ultraball" ||
    id === "masterball" ||
    id.startsWith("baya_") ||
    id === "pocion_maxima" ||
    id === "caramelo_raro" ||
    id.startsWith("piedra_") ||
    id.startsWith("huevo_")
  );
}

export function getItemDef(id: string): ItemDef | undefined {
  return ITEMS_REGISTRY[id];
}

export function getAllItems(): ItemDef[] {
  return Object.values(ITEMS_REGISTRY);
}

/** Devuelve la lista compatible con el catálogo original de la tienda */
export function getShopItemsList(): { id: string; name: string; price: number; desc: string }[] {
  return getAllItems()
    .filter((i) => i.price !== undefined && i.price > 0)
    .map((i) => ({
      id: i.id,
      name: `${i.name} ${i.emoji}`,
      price: i.price!,
      desc: i.description,
    }));
}

export function getCollection(id: string): ItemCollection | undefined {
  return COLLECTIONS.find((c) => c.id === id);
}

export function getUserCollectionProgress(
  inv: Record<string, number>,
  collectionId: string,
): { collection: ItemCollection; total: number; owned: number; pct: number; items: { def: ItemDef; count: number }[] } | null {
  const col = getCollection(collectionId);
  if (!col) return null;
  const items = col.itemIds.map((id) => {
    const def = getItemDef(id)!;
    const count = inv[id] ?? 0;
    return { def, count };
  });
  const owned = items.filter((i) => i.count > 0).length;
  const total = items.length;
  const pct = Math.round((owned / total) * 100);
  return { collection: col, total, owned, pct, items };
}

